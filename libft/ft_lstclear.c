#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*begin;
	t_list	*curr;
	t_list	*next;

	if (!lst || !del || !*lst)
		return ;
	begin = *lst;
	curr = begin;
	while (curr)
	{
		next = curr->next;
		del(curr->content);
		free(curr);
		curr = next;
	}
	*lst = NULL;
}
